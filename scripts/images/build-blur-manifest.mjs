/**
 * Generates tiny base64 LQIP (blur) data URLs for non-hero catalog photos so
 * next/image can paint an instant placeholder while the static variant loads.
 * Heroes are intentionally excluded (they render real pixels, no blur), and
 * finishes are excluded (they paint their hex swatch color instantly).
 *
 * Run: node scripts/images/build-blur-manifest.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

let sharp;
try {
  sharp = (await import("sharp")).default;
} catch {
  console.warn("sharp is not installed; skipping blur manifest generation.");
  process.exit(0);
}

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..", "..");
const publicDir = path.join(root, "public");

// Non-hero, non-finish photo sets that route through CatalogImage / tiles.
const DIRS = [
  "images/catalog/rooms",
  "images/catalog/collections",
  "images/catalog/door-styles",
  "images/catalog/products",
  "images/catalog/hardware",
  "images/catalog/accessories",
  "images/gallery",
];

const VARIANT_RE = /-\d+\.webp$/;
const isBaseWebp = (name) => name.endsWith(".webp") && !VARIANT_RE.test(name);

const manifest = {};
let count = 0;

async function processDir(dirRel) {
  const absDir = path.join(publicDir, dirRel);
  if (!fs.existsSync(absDir)) return;
  for (const name of fs.readdirSync(absDir)) {
    if (!isBaseWebp(name)) continue;
    const absFile = path.join(absDir, name);
    try {
      const buf = await sharp(absFile)
        .resize(16, 16, { fit: "inside" })
        .webp({ quality: 45 })
        .toBuffer();
      manifest[`/${dirRel}/${name}`] = `data:image/webp;base64,${buf.toString("base64")}`;
      count += 1;
    } catch {
      // skip unreadable files
    }
  }
}

async function main() {
  for (const d of DIRS) {
    await processDir(d);
  }

  const sortedKeys = Object.keys(manifest).sort();
  const entries = sortedKeys
    .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(manifest[k])},`)
    .join("\n");

  const outPath = path.join(root, "shared", "generated", "imageBlur.ts");
  const contents = `/**
 * AUTO-GENERATED by scripts/images/build-blur-manifest.mjs - do not edit.
 * Maps a base public image path to a tiny base64 blur placeholder (LQIP).
 */
export const IMAGE_BLUR: Record<string, string> = {
${entries}
};

/** Returns a blurDataURL for an image path, or undefined if none exists. */
export function getBlurDataURL(src?: string): string | undefined {
  if (!src) return undefined;
  return IMAGE_BLUR[src];
}
`;
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, contents);

  console.log(`Blur manifest: ${count} entries -> ${path.relative(root, outPath)}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
