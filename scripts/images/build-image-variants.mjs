/**
 * Pre-generates fixed-width WebP variants for catalog + marketing images and
 * writes a manifest so a custom next/image loader can serve them statically
 * (no runtime optimization, immune to autoscale cold starts).
 *
 * Run: node scripts/images/build-image-variants.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

let sharp;
try {
  sharp = (await import("sharp")).default;
} catch {
  console.warn("sharp is not installed; skipping image variant generation.");
  process.exit(0);
}

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..", "..");
const publicDir = path.join(root, "public");
const QUALITY = 82;

/** Directories (relative to /public) and the width ladder to generate for each. */
const TARGETS = [
  { dir: "images/marketing", widths: [768, 1280, 1920] },
  { dir: "images/catalog/rooms", widths: [320, 640, 1080] },
  { dir: "images/catalog/collections", widths: [320, 640, 1080] },
  { dir: "images/catalog/door-styles", widths: [320, 640] },
  { dir: "images/catalog/products", widths: [320, 640] },
  { dir: "images/catalog/finishes", widths: [160, 320, 640] },
  { dir: "images/catalog/hardware", widths: [160, 320, 640] },
  { dir: "images/catalog/accessories", widths: [160, 320, 640] },
  { dir: "images/gallery", widths: [640, 1080, 1920] },
  { dir: "images/blog", widths: [640, 1080, 1920] },
];

const VARIANT_RE = /-\d+\.webp$/;
const isBaseWebp = (name) => name.endsWith(".webp") && !VARIANT_RE.test(name);

const manifest = {};
let generated = 0;
let skipped = 0;

async function processDir(dirRel, widths) {
  const absDir = path.join(publicDir, dirRel);
  if (!fs.existsSync(absDir)) return;
  for (const name of fs.readdirSync(absDir)) {
    if (!isBaseWebp(name)) continue;
    const absFile = path.join(absDir, name);
    const base = name.replace(/\.webp$/, "");
    let maxW = 0;
    try {
      maxW = (await sharp(absFile).metadata()).width ?? 0;
    } catch {
      continue;
    }
    const available = [];
    for (const w of widths) {
      if (maxW && w > maxW) continue;
      const destAbs = path.join(absDir, `${base}-${w}.webp`);
      if (!fs.existsSync(destAbs)) {
        try {
          await sharp(absFile).resize(w).webp({ quality: QUALITY }).toFile(destAbs);
          generated += 1;
        } catch {
          continue;
        }
      } else {
        skipped += 1;
      }
      available.push(w);
    }
    if (available.length > 0) {
      manifest[`/${dirRel}/${name}`] = available.sort((a, b) => a - b);
    }
  }
}

async function main() {
  for (const t of TARGETS) {
    await processDir(t.dir, t.widths);
  }

  const sortedKeys = Object.keys(manifest).sort();
  const entries = sortedKeys
    .map((k) => `  ${JSON.stringify(k)}: [${manifest[k].join(", ")}],`)
    .join("\n");

  const outPath = path.join(root, "shared", "generated", "imageVariants.ts");
  const contents = `/**
 * AUTO-GENERATED by scripts/images/build-image-variants.mjs - do not edit.
 * Maps a base public image path to the fixed WebP variant widths that exist on
 * disk, so lib/images/staticVariantLoader.ts can serve them without the runtime
 * image optimizer.
 */
export const IMAGE_VARIANTS: Record<string, number[]> = {
${entries}
};
`;
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, contents);

  console.log(
    `Image variants: generated ${generated}, reused ${skipped}, manifest entries ${sortedKeys.length}`,
  );
  console.log(`Wrote ${path.relative(root, outPath)}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
