/**
 * Generates shared/generated/imageIdentity.ts: a 64-bit difference hash for
 * every base photograph under public/images. One photograph is stored under
 * several file names, so pages compare pictures by this hash, not by path,
 * when they must not show the same picture twice.
 *
 * Run: node scripts/images/build-image-identity.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

let sharp;
try {
  sharp = (await import("sharp")).default;
} catch {
  console.warn("sharp is not installed; skipping image identity generation.");
  process.exit(0);
}

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..", "..");
const publicDir = path.join(root, "public");

const VARIANT_RE = /-(320|640|768|1080|1280|1920|og)\.(webp|jpg|jpeg|png)$/;
const PHOTO_RE = /\.(webp|jpg|jpeg|png)$/i;

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return PHOTO_RE.test(entry.name) && !VARIANT_RE.test(entry.name) ? [full] : [];
  });
}

async function fingerprint(file) {
  const pixels = await sharp(file).greyscale().resize(9, 8, { fit: "fill" }).raw().toBuffer();
  let hex = "";
  for (let y = 0; y < 8; y += 1) {
    let byte = 0;
    for (let x = 0; x < 8; x += 1) byte = (byte << 1) | (pixels[y * 9 + x] > pixels[y * 9 + x + 1] ? 1 : 0);
    hex += byte.toString(16).padStart(2, "0");
  }
  return hex;
}

const manifest = {};
for (const file of walk(path.join(publicDir, "images")).sort()) {
  try {
    manifest[`/${path.relative(publicDir, file).split(path.sep).join("/")}`] = await fingerprint(file);
  } catch {
    // skip unreadable files
  }
}

const entries = Object.keys(manifest)
  .sort()
  .map((key) => `  ${JSON.stringify(key)}: "${manifest[key]}",`)
  .join("\n");

fs.writeFileSync(
  path.join(root, "shared", "generated", "imageIdentity.ts"),
  `/**
 * AUTO-GENERATED by scripts/images/build-image-identity.mjs - do not edit.
 * Maps a base public image path to a 64-bit difference hash of the picture.
 */
export const IMAGE_IDENTITY: Record<string, string> = {
${entries}
};
`,
);
console.log(`Wrote image identity for ${Object.keys(manifest).length} photographs`);
